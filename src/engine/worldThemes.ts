const CUSTOM_THEMES_STORAGE_KEY = "dice-chaos-compass-world-themes-v1";
const LEGACY_CUSTOM_THEMES_STORAGE_KEY = "dice-chaos-maps-world-themes-v1";

export function getWorldThemeById(themeId: string): WorldThemeConfig {
  const custom = loadCustomWorldThemes();
  const foundCustom = custom.find((t) => t.id === themeId);
  if (foundCustom) return { ...foundCustom };
  return { ...(WORLD_THEMES.find((t) => t.id === themeId) ?? WORLD_THEMES[0]) };
}

export function loadCustomWorldThemes(): WorldThemeConfig[] {
  try {
    const raw =
      localStorage.getItem(CUSTOM_THEMES_STORAGE_KEY) ??
      localStorage.getItem(LEGACY_CUSTOM_THEMES_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveCustomWorldTheme(theme: WorldThemeConfig): WorldThemeConfig[] {
  const existing = loadCustomWorldThemes().filter((t) => t.id !== theme.id);
  const next = [theme, ...existing].slice(0, 16);
  try {
    localStorage.setItem(CUSTOM_THEMES_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // Ignore storage errors
  }
  return next;
}
