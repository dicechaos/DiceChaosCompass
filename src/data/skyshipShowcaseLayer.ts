function mkSkyProp(
  id: string,
  assetId: string,
  x: number,
  y: number,
  w: number,
  h: number,
  opts?: {
    rot?: number;
    z?: number;
    shadow?: boolean;
    flipX?: boolean;
    flipY?: boolean;
    opacity?: number;
  },
): ObjectStamp {
  return {
    id,
    assetId,
    x,
    y,
    widthCells: w,
    heightCells: h,
    rotationRad: opts?.rot ?? 0,
    flipX: opts?.flipX ?? false,
    flipY: opts?.flipY ?? false,
    opacity: opts?.opacity ?? 1,
    castsShadow: opts?.shadow ?? true,
    locked: false,
    recolor: { ...DEFAULT_RECOLOR },
    zOrder: opts?.z ?? 40,
  };
}

